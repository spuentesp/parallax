// Publishes a machine-generated architecture page to Confluence.
//
// Kept free of Forge imports so it can be tested locally: the caller injects
// `cf(path, init)`, a function that performs a Confluence REST request and
// returns a fetch-style Response. In production that is api.asUser().requestConfluence.
//
// Safety rules:
//  - Pages are found by title inside the given space.
//  - A page is only ever UPDATED if it carries our marker property. A page with the
//    same title that we did not create is never touched.

export const MARKER_KEY = 'parallax-generated';
export const LABELS = ['parallax', 'lain', 'machine-made'];

// Escape text before placing it in Confluence storage-format XHTML.
export function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

// A coloured status lozenge, used as a visible "machine made" tag.
const lozenge = (title, colour) =>
  `<ac:structured-macro ac:name="status"><ac:parameter ac:name="title">${esc(title)}</ac:parameter><ac:parameter ac:name="colour">${colour}</ac:parameter></ac:structured-macro>`;

const row = (cells, header = false) =>
  `<tr>${cells.map((c) => `<${header ? 'th' : 'td'}>${c}</${header ? 'th' : 'td'}>`).join('')}</tr>`;
const table = (head, rows) =>
  `<table><tbody>${row(head, true)}${rows.map((r) => row(r)).join('')}</tbody></table>`;

// Human wording for the evidence label coming from the graph.
const evidence = (provenance) =>
  provenance === 'deterministic'
    ? 'Proven by code'
    : `Inferred (${esc(provenance ?? 'unknown')}), verify before relying on it`;

export const pageTitle = (node) => `Service architecture: ${node.label}`;

// Build the storage-format body for one service from a node-impact summary.
export function buildServicePage({ impact, workspace, generatedAt }) {
  const { node, consumers, providers, groups } = impact;
  const repo = (workspace?.repos ?? []).find((r) => r.id === node.repo);

  const consumerRows = consumers.map((c) => [
    `<strong>${esc(c.service)}</strong>`,
    esc(c.repo),
    evidence(c.provenance),
    esc(c.usages),
    c.endpointsUsed.length
      ? `<ul>${c.endpointsUsed.map((e) => `<li><code>${esc(e.endpoint)}</code> (${esc(e.usages)})</li>`).join('')}</ul>`
      : '-',
    c.sampleCallSites.length
      ? `<ul>${c.sampleCallSites.map((s) => `<li><code>${esc(s.repo)}:${esc(s.path)}:${esc(s.line)}</code></li>`).join('')}</ul>`
      : '-',
  ]);

  const groupRows = groups.map((g) => [esc(g.label), esc(g.contractKind ?? g.group ?? ''), esc(g.contracts ?? '')]);

  return [
    `<ac:structured-macro ac:name="info"><ac:rich-text-body><p>${lozenge('MACHINE MADE', 'Purple')} ${lozenge('PARALLAX', 'Blue')} ${lozenge('LAIN', 'Grey')}</p>` +
      `<p>This page was generated automatically by Parallax from the Lain code graph. Do not edit it by hand: changes are overwritten the next time it is generated.</p></ac:rich-text-body></ac:structured-macro>`,
    `<h2>Overview</h2>`,
    table(
      ['Service', 'Repository', 'Endpoints', 'Consumer services'],
      [[`<strong>${esc(node.label)}</strong>`, esc(node.repo), esc(impact.endpointCount ?? node.endpoints), esc(consumers.length)]],
    ),
    `<h2>Who depends on this service</h2>`,
    consumers.length
      ? table(['Consumer', 'Repository', 'Evidence', 'Usages', 'Endpoints used', 'Sample call sites'], consumerRows)
      : '<p>No consumer was found in the analysed repositories.</p>',
    providers.length
      ? `<h2>What this service depends on</h2>${table(['Provider', 'Repository', 'Evidence', 'Usages'], providers.map((p) => [esc(p.service), esc(p.repo), evidence(p.provenance), esc(p.usages)]))}`
      : '',
    `<h2>Contract groups</h2>`,
    groups.length ? table(['Group', 'Kind', 'Contracts'], groupRows) : '<p>No contract groups reported.</p>',
    `<h2>Evidence</h2>`,
    table(
      ['Workspace', 'Repository commit', 'Generated at', 'Generated by'],
      [[esc(workspace?.name ?? workspace?.id ?? ''), repo ? `<code>${esc(repo.id)}@${esc(repo.sha)}</code>` : 'unknown', esc(generatedAt), 'Parallax (powered by Lain)']],
    ),
  ].join('');
}

const json = { 'Content-Type': 'application/json', Accept: 'application/json' };

async function mustOk(res, what) {
  if (res.ok) return res;
  const detail = (await res.text()).slice(0, 300);
  const err = new Error(`${what} failed: HTTP ${res.status} ${detail}`);
  err.status = res.status;
  throw err;
}

// Create or update the service page. Returns { action, pageId, title, webui }.
export async function publishServicePage({ cf, spaceKey, impact, workspace, now = new Date() }) {
  const spaces = await mustOk(await cf(`/wiki/api/v2/spaces?keys=${encodeURIComponent(spaceKey)}`), 'Space lookup');
  const space = (await spaces.json()).results?.[0];
  if (!space) return { error: `No Confluence space with key '${spaceKey}'.` };

  const title = pageTitle(impact.node);
  const body = buildServicePage({ impact, workspace, generatedAt: now.toISOString() });

  const found = await mustOk(
    await cf(`/wiki/api/v2/spaces/${space.id}/pages?title=${encodeURIComponent(title)}&limit=5`),
    'Page lookup',
  );
  const existing = (await found.json()).results?.[0];

  let pageId;
  let action;
  let webui;
  if (existing) {
    // Only touch pages we created: they carry the marker property.
    const props = await mustOk(
      await cf(`/wiki/api/v2/pages/${existing.id}/properties?key=${MARKER_KEY}`),
      'Marker lookup',
    );
    if (!(await props.json()).results?.length) {
      return {
        error: `A page titled '${title}' already exists in '${spaceKey}' but was not generated by Parallax. Refusing to overwrite it.`,
        pageId: existing.id,
      };
    }
    const current = await (await mustOk(await cf(`/wiki/api/v2/pages/${existing.id}`), 'Page read')).json();
    const updated = await mustOk(
      await cf(`/wiki/api/v2/pages/${existing.id}`, {
        method: 'PUT',
        headers: json,
        body: JSON.stringify({
          id: existing.id,
          status: 'current',
          title,
          body: { representation: 'storage', value: body },
          version: { number: current.version.number + 1, message: 'Regenerated by Parallax' },
        }),
      }),
      'Page update',
    );
    const page = await updated.json();
    pageId = page.id;
    webui = page._links?.webui;
    action = 'updated';
  } else {
    const created = await mustOk(
      await cf('/wiki/api/v2/pages', {
        method: 'POST',
        headers: json,
        body: JSON.stringify({ spaceId: space.id, status: 'current', title, body: { representation: 'storage', value: body } }),
      }),
      'Page create',
    );
    const page = await created.json();
    pageId = page.id;
    webui = page._links?.webui;
    action = 'created';
    // Mark the page as ours so later runs may update it.
    await mustOk(
      await cf(`/wiki/api/v2/pages/${pageId}/properties`, {
        method: 'POST',
        headers: json,
        body: JSON.stringify({ key: MARKER_KEY, value: { generator: 'parallax', node: impact.node.nodeId, workspace: workspace?.id } }),
      }),
      'Marker write',
    );
  }

  // Labels are idempotent: re-adding an existing label is harmless.
  await mustOk(
    await cf(`/wiki/rest/api/content/${pageId}/label`, {
      method: 'POST',
      headers: json,
      body: JSON.stringify(LABELS.map((name) => ({ prefix: 'global', name }))),
    }),
    'Label write',
  );

  return { action, pageId, title, space: spaceKey, webui, labels: LABELS };
}
